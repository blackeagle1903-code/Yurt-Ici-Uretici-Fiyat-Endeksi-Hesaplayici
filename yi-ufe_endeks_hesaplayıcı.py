def para_ve_enflasyon_hesapla():
    # Güncel sistem tarihini otomatik al
    bugun = datetime.now()
    guncel_yil = bugun.year
    guncel_ay = bugun.month
    
    print("--- Yİ-ÜFE Para Değeri ve Endeks Hesaplama Aracı ---")
    print(f"Sistem Güncel Tarihi: {guncel_ay:02d}.{guncel_yil}\n")
    
    # 1. Kullanıcıdan para miktarını al
    try:
        anappara = float(input("Başlangıç para miktarını girin (Örn: 1000): "))
    except ValueError:
        print("Geçersiz para miktarı girdiniz.")
        return

    # 2. Kullanıcıdan tarihi AA.YYYY formatında iste (Varsayılan: 01.2010)
    tarih_girdisi = input("Başlangıç tarihini girin [Örnek: 01.2010]: ").strip()
    
    if not tarih_girdisi:
        tarih_girdisi = "01.2010"

    try:
        parca = tarih_girdisi.split('.')
        ay = int(parca[0])
        yil = int(parca[1])
    except (IndexError, ValueError):
        print("Tarih formatı hatalı! Lütfen 01.2010 şeklinde giriniz.")
        return

    data = parse_raw_data("")
    
    # Kontroller
    if yil not in data or ay < 1 or ay > len(data[yil]):
        print(f"Hata: {tarih_girdisi} dönemi için veri tabanında endeks bulunamadı.")
        return

    baslangic_endeks = data[yil][ay - 1]
    
    # En güncel veriyi baz alalım (Mevcut yıl/ay veri tabanında yoksa en son dolu ayı seç)
    if guncel_yil not in data:
        guncel_yil = max(data.keys())
    
    if guncel_ay > len(data[guncel_yil]):
        guncel_ay = len(data[guncel_yil])
        
    guncel_endeks = data[guncel_yil][guncel_ay - 1]
    
    # Hesaplamalar
    degisim_orani = ((guncel_endeks / baslangic_endeks) - 1) * 100
    guncel_deger = anappara * (guncel_endeks / baslangic_endeks)
    
    print("\n" + "="*45)
    print(f" Başlangıç Tarihi       : {ay:02d}.{yil} (Endeks: {baslangic_endeks})")
    print(f" Güncel Referans Tarih  : {guncel_ay:02d}.{guncel_yil} (Endeks: {guncel_endeks})")
    print(f" Başlangıç Para         : {anappara:,.2f} TL")
    print("-" * 45)
    print(f" Yİ-ÜFE Değişimi        : %{degisim_orani:,.2f}")
    print(f" Paranın Güncel Değeri  : {guncel_deger:,.2f} TL")
    print("="*45)

if __name__ == "__main__":
    para_ve_enflasyon_hesapla()